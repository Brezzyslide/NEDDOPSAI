/**
 * OpenClaw Adapter Contract Tests
 *
 * Investigation conclusion (August 2026):
 *   The "Cannot read properties of undefined (reading 'id')" crash in the
 *   Chief of Staff → Operations Manager task was NOT caused by the OpenClaw
 *   update. Evidence:
 *
 *   1. The CoS → OM standard execution path (dispatchWorkExecution →
 *      workExecutionPipelineService.executeWork) does NOT call
 *      engine.submitExecution() — it uses the AI gateway (OpenAI / rule-based).
 *      OpenClaw is only invoked via the separate POST /tasks/:id/submit route.
 *
 *   2. openClawExecutionEngine.submitExecution accesses brokerResponse.status,
 *      brokerResponse.reason, brokerResponse.runtimeExecutionId, and
 *      brokerResponse.estimatedStartAt. There is no .id access on the broker
 *      response object.
 *
 *   3. The recent OpenClaw updates (commits 841ec7e and caa0ae3) changed
 *      LiveGatewayAdapter internals and added cross-platform adapters in the
 *      Electron app. Neither commit changed:
 *        - executions.ts (the broker route that forms the HTTP response)
 *        - OpenClawSubmissionResponse (unchanged type)
 *        - OpenClawWebhookEvent (unchanged type)
 *        - BrokerWebhookEvent.eventId (still generated by randomUUID on the broker)
 *
 *   4. The actual crash was the addMessage/SSE handler bug (return msg! silently
 *      returned undefined when DB RETURNING yielded 0 rows), fixed in
 *      regression-undefined-agent-message.test.ts.
 *
 * These tests lock down the OpenClaw adapter contract so any future
 * OpenClaw update that drifts the response shape is caught before production.
 */

